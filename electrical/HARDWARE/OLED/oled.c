/*==========================================================
  顯示 ASCII 字符串
==========================================================*/
void OLED_ShowString(uint8_t x,
                     uint8_t y,
                     char *str)
{
    uint8_t i;
    uint8_t page;

    page = y / 8;

    OLED_WriteCommand(0xB0 + page);

    OLED_WriteCommand(0x00 + (x & 0x0F));
    OLED_WriteCommand(0x10 + ((x >> 4) & 0x0F));

    while(*str)
    {
        char c = *str;

        if(c < 32 || c > 126)
        {
            c = '?';
        }

        for(i = 0; i < 5; i++)
        {
            uint8_t column = Font5x7[c - 32][i];

            OLED_WriteData(&column, 1);
        }

        /* 字符间留一个空列 */
        {
            uint8_t space = 0x00;

            OLED_WriteData(&space, 1);
        }

        str++;
    }
}